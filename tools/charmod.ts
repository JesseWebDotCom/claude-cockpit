// Generates hooks/charsdata.ts from assets/characters-frames.js and assets/characters.js, so the pane loads the shared characters
// with a plain static import (the pane engine cannot dynamically import a classic script). Run: bun tools/charmod.ts
import { readFileSync, writeFileSync } from 'node:fs'
const root = new URL('..', import.meta.url).pathname
const frames = readFileSync(root + 'assets/characters-frames.js', 'utf8').replace(/^if \(typeof module.*$/m, '')
let shared = readFileSync(root + 'assets/characters.js', 'utf8')
shared = shared.replace(/^const CHAR_FR = .*$/m, 'const CHAR_FR = CHAR_FRAMES')
const m = shared.match(/^if \(typeof module !== 'undefined'\) module\.exports = (\{.*\})\s*$/m)
if (m === null) throw new Error('characters.js has no module.exports line')
shared = shared.replace(/^if \(typeof module.*$/m, '')
const out = `// GENERATED by tools/charmod.ts from assets/characters-frames.js and assets/characters.js. Do not edit: run \`bun tools/charmod.ts\`.
// @ts-nocheck
export function buildChars(): any {
${frames}
${shared}
return ${m[1]}
}
`
writeFileSync(root + 'hooks/charsdata.ts', out)
console.log('wrote hooks/charsdata.ts', out.length)
